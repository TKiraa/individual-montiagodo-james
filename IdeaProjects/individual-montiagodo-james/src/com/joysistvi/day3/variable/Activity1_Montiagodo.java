package com.joysistvi.day3.variable;

public class Activity1_Montiagodo {

    public static void main(String[] args){

        byte age = 20;
        System.out.println("age: " + age);

        short num = 300;
        System.out.println("num: " + num);

        int num2 = 10_0000;
        System.out.println("num2: " + num2);

        long num3 = 50000000000L;
        System.out.println("num3: " + num3);

        float average =90.90f;
        System.out.println("average: " + average);

        double price = 20.555555d;
        System.out.println("price: " + price);

        boolean is_active = false;

        char middleInitial= 'A';
        System.out.println("middleInitial: " + middleInitial);

        String firstName = "James";
        System.out.println("firstName: " + firstName);

        String lastName = "Montiagodo";
        System.out.println("lastName: " + lastName);

        System.out.println("Full Name: " + lastName + ", " + firstName + " " + middleInitial + ".");
    }
}